const API_BASE = 'https://dataglow.ai/datax-api';

/**
 * Generate rules dynamically using the live Azure OpenAI Rule Engine.
 * @param {Object} params
 * @param {string} params.prompt - User natural language prompt describing rules
 * @param {Array<string>} params.columns - Schema column names discovered from table
 * @param {string} params.tableName - Name of target database table (e.g. MARA, 0IC_C03, EKKO)
 * @param {string} params.engine - Database engine (sap_bw, postgres, mongodb)
 * @returns {Promise<Array<Object>>} Synthesized rules
 */
export async function callAiRuleEngine({
  prompt,
  columns = [],
  tableName = '',
  engine = 'sap_bw'
}) {
  try {
    const res = await fetch(`${API_BASE}/rules/generate`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json'
      },
      body: JSON.stringify({
        tableName: tableName || 'source_table',
        columns: columns || [],
        prompt: prompt || 'Validate required fields and logical constraints.',
        engine: engine || 'sap_bw'
      })
    });

    if (res.ok) {
      const data = await res.json();
      if (data.success && Array.isArray(data.rules) && data.rules.length > 0) {
        return data.rules.map((r, idx) => ({
          id: r.id || `r_ai_${idx + 1}`,
          name: r.name || `Rule ${idx + 1}`,
          field: r.field || (columns[idx % columns.length] || 'FIELD'),
          severity: r.severity || (idx < 2 ? 'Critical' : 'Warning'),
          condition: r.condition || r.code,
          code: r.code || r.condition,
          desc: r.desc || 'Automated rule generated by DataX AI Engine',
          selected: true,
          badge: data.engine || 'Azure OpenAI (gpt-5-mini)'
        }));
      }
    }
  } catch (err) {
    console.warn('Live AI Rule Engine call failed, utilizing local semantic synthesizer:', err);
  }

  // Fallback dynamic synthesis: extracts semantic constraints directly from prompt & columns
  return synthesizeSemanticRules({ prompt, columns, tableName });
}

/**
 * Dynamic fallback semantic synthesizer (operates without static hardcoded table catalogs)
 */
function synthesizeSemanticRules({ prompt, columns, tableName }) {
  const p = (prompt || '').toLowerCase();
  const rules = [];
  const colList = columns && columns.length > 0 ? columns : ['RECORD_ID', 'VALUE', 'STATUS'];

  // Check for presence / null checks
  if (p.includes('mandatory') || p.includes('missing') || p.includes('required') || p.includes('not null') || p.includes('blank')) {
    const primary = colList[0];
    rules.push({
      id: `r_not_null_${primary.toLowerCase()}`,
      name: `Mandatory ${primary}`,
      field: primary,
      severity: 'Critical',
      condition: `${primary} IS NOT NULL AND LENGTH(TRIM(${primary})) > 0`,
      code: `${primary} IS NOT NULL AND LENGTH(TRIM(${primary})) > 0`,
      desc: `Guarantees ${primary} is present and non-empty for every record in ${tableName}.`,
      selected: true,
      badge: 'Synthesized: Null check'
    });
  }

  // Check for uniqueness
  if (p.includes('duplicate') || p.includes('unique')) {
    const primary = colList[0];
    rules.push({
      id: `r_unique_${primary.toLowerCase()}`,
      name: `Unique Key ${primary}`,
      field: primary,
      severity: 'Critical',
      condition: `COUNT(${primary}) == COUNT(DISTINCT ${primary})`,
      code: `COUNT(${primary}) == COUNT(DISTINCT ${primary})`,
      desc: `Enforces strict deduplication across primary key ${primary}.`,
      selected: true,
      badge: 'Synthesized: Uniqueness'
    });
  }

  // Check for positive / range bounds
  if (p.includes('positive') || p.includes('> 0') || p.includes('greater than')) {
    const numCol = colList.find(c => {
      const u = c.toUpperCase();
      return u.includes('QTY') || u.includes('QUANTITY') || u.includes('PRICE') || u.includes('WEIGHT') || u.includes('AMOUNT') || u.includes('BALANCE');
    }) || colList[1] || colList[0];

    rules.push({
      id: `r_positive_${numCol.toLowerCase()}`,
      name: `Positive ${numCol}`,
      field: numCol,
      severity: 'Critical',
      condition: `${numCol} > 0`,
      code: `${numCol} > 0`,
      desc: `Enforces strictly positive numerical bounds on ${numCol}.`,
      selected: true,
      badge: 'Synthesized: Numeric bound'
    });
  }

  // Check for allowed values / whitelist
  if (p.includes('allowed') || p.includes('active') || p.includes('status') || p.includes('whitelist')) {
    const statusCol = colList.find(c => {
      const u = c.toUpperCase();
      return u.includes('STATUS') || u.includes('TYPE') || u.includes('ROLE') || u.includes('PLANT');
    }) || colList[Math.min(2, colList.length - 1)];

    rules.push({
      id: `r_allowed_${statusCol.toLowerCase()}`,
      name: `Allowed Domain for ${statusCol}`,
      field: statusCol,
      severity: 'Warning',
      condition: `${statusCol} IN ('active', 'verified', 'approved')`,
      code: `${statusCol} IN ('active', 'verified', 'approved')`,
      desc: `Restricts ${statusCol} to authorized enterprise enumeration values.`,
      selected: true,
      badge: 'Synthesized: Whitelist'
    });
  }

  // If prompt has specific column mentions, add custom rule
  for (const col of colList.slice(0, 3)) {
    if (!rules.some(r => r.field === col)) {
      rules.push({
        id: `r_check_${col.toLowerCase()}`,
        name: `Data Quality Check on ${col}`,
        field: col,
        severity: 'Warning',
        condition: `${col} IS NOT NULL`,
        code: `${col} IS NOT NULL`,
        desc: `Ensures field integrity and format compliance for ${col} in ${tableName}.`,
        selected: true,
        badge: 'Synthesized: Semantic'
      });
    }
  }

  return rules;
}

export function getDefaultPromptForTable(tableName = '', engine = 'sap_bw', columns = []) {
  const normTable = (tableName || '').toUpperCase();
  const colUpper = (columns || []).map(c => (typeof c === 'string' ? c.toUpperCase() : String(c?.name || '').toUpperCase()));

  if (colUpper.length > 0) {
    const suggestions = [];

    // 1. Primary Identifier
    const idCol = colUpper.find(c => 
      c.endsWith('_ID') || c.endsWith('_NO') || c.endsWith('_NUM') || 
      c === 'ID' || c === 'MATNR' || c === 'PO_NUMBER' || c === 'MATERIAL_DOC' || c === 'EBELN'
    ) || colUpper[0];
    if (idCol) {
      suggestions.push(`${idCol} is mandatory and must be unique`);
    }

    // 2. Weight cross-column constraint
    const grossWeight = colUpper.find(c => c === 'BRGEW' || c.includes('GROSS_WEIGHT'));
    const netWeight = colUpper.find(c => c === 'NTGEW' || c.includes('NET_WEIGHT'));
    if (grossWeight && netWeight) {
      suggestions.push(`${grossWeight} must be strictly greater than ${netWeight}`);
    }

    // 3. Multiplicative sanity (Total = Qty * Price)
    const qtyCol = colUpper.find(c => c === 'QUANTITY' || c === 'MENGE' || c.includes('QTY'));
    const priceCol = colUpper.find(c => c === 'UNIT_PRICE' || c === 'NETPR' || c.includes('PRICE'));
    const totalCol = colUpper.find(c => c === 'TOTAL_AMOUNT' || c === 'DMBTR' || c.includes('TOTAL'));
    if (qtyCol && priceCol && totalCol) {
      suggestions.push(`${totalCol} must equal ${qtyCol} multiplied by ${priceCol}`);
    } else if (qtyCol) {
      suggestions.push(`${qtyCol} must be strictly positive`);
    }

    // 4. Plant / Warehouse / Movement / Status domains
    const plantCol = colUpper.find(c => c === 'DELIVERY_PLANT' || c === 'WERKS' || c.includes('PLANT'));
    if (plantCol) {
      suggestions.push(`${plantCol} must conform to authorized enterprise plant codes`);
    }

    const mvtCol = colUpper.find(c => c === 'BWART' || c.includes('MOVEMENT_TYPE'));
    if (mvtCol) {
      suggestions.push(`${mvtCol} must be a valid SAP movement type`);
    }

    const typeCol = colUpper.find(c => c === 'MTART' || c.includes('MATERIAL_TYPE'));
    if (typeCol) {
      suggestions.push(`${typeCol} must be an authorized material category`);
    }

    const emailCol = colUpper.find(c => c === 'EMAIL' || c.includes('EMAIL'));
    if (emailCol) {
      suggestions.push(`${emailCol} must have a valid RFC format`);
    }

    const balanceCol = colUpper.find(c => c.includes('BALANCE') || c.includes('AMOUNT'));
    if (balanceCol && !suggestions.some(s => s.includes(balanceCol))) {
      suggestions.push(`${balanceCol} cannot be negative`);
    }

    if (suggestions.length > 0) {
      return suggestions.join('. ') + '.';
    }
  }

  // Schema-aware fallback based on table pattern
  if (normTable.includes('MARA')) {
    return 'Material number MATNR is mandatory. Gross weight BRGEW must be strictly greater than net weight NTGEW. Valid material type MTART required.';
  }
  if (normTable.includes('0IC_C03') || normTable.includes('MOVE')) {
    return 'Movement quantity MENGE must be strictly positive. Movement type BWART must be valid. Plant WERKS must be authorized.';
  }
  if (normTable.includes('EKKO')) {
    return 'Purchasing document EBELN is mandatory. Company code BUKRS and vendor LIFNR must be valid.';
  }
  if (normTable.includes('EKPO')) {
    return 'Line item quantities MENGE and net prices NETPR must be positive. Receiving plant WERKS must be authorized.';
  }
  if (normTable.includes('0PUR') || normTable.includes('PO')) {
    return 'PO_NUMBER is mandatory. QUANTITY and UNIT_PRICE must be positive. DELIVERY_PLANT must be valid.';
  }
  if (normTable.includes('USER') || normTable.includes('CUSTOMER')) {
    return 'Email must have valid RFC format. Full name cannot be blank. Role must be admin, analyst, manager, or viewer. Account balance cannot be negative.';
  }

  return `Ensure primary keys in ${tableName || 'table'} are mandatory and unique, numerical values are positive, and categorical fields conform to authorized domains.`;
}
